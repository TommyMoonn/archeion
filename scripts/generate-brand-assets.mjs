import fs from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const directory = path.join(root, "src/assets/brand");
const approvedImages = new Map([
  ["archeion-logo-dark.png", "89832875ec9f7ce1fe0ef821fef0f6c8e484450ee8c6b058879170ae94e6902d"],
  ["archeion-logo-light.png", "49fe7ec9e4128dd1b06b0ade96faafc4ab77f7051c0091869ae2e14f26e1e7ac"],
  [
    "archeion-wordmark-dark.png",
    "e3f63c98a19f8afb557a01afae9ddee95dd7737647d77341da0c9b0659ab9a13",
  ],
  [
    "archeion-wordmark-light.png",
    "19e96385494927c9c4c9b5d4da388eeb62b560c7db8dc5a620bca8dd1a26e915",
  ],
]);

for (const [name, hash] of approvedImages) {
  const actual = createHash("sha256")
    .update(fs.readFileSync(path.join(directory, name)))
    .digest("hex");
  if (actual !== hash) throw new Error(`Approved artwork changed: ${name}`);
}

const source = fs.readFileSync(path.join(directory, "archeion-symbol.svg"), "utf8");
const paths = source.slice(source.indexOf("\n") + 1, source.lastIndexOf("</svg>")).trim();
const check = process.argv.includes("--check");
let stale = false;
for (const [surface, color] of [
  ["light", "#121212"],
  ["dark", "#ffffff"],
]) {
  const name = `archeion-symbol-on-${surface}.svg`;
  const contents = `<!-- Generated by scripts/generate-brand-assets.mjs. Edit archeion-symbol.svg. -->\n<svg xmlns="http://www.w3.org/2000/svg" viewBox="100 90 300 300" fill="${color}">\n${paths}\n</svg>\n`;
  const destination = path.join(directory, name);
  if (check) {
    if (!fs.existsSync(destination) || fs.readFileSync(destination, "utf8") !== contents) {
      console.error(`Stale brand asset: ${path.relative(root, destination)}`);
      stale = true;
    }
  } else {
    fs.writeFileSync(destination, contents);
  }
}
if (stale) process.exitCode = 1;
else
  console.log(
    check
      ? "Approved artwork and derived brand assets verified."
      : "Generated brand symbol exports.",
  );
