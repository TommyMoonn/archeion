import { readFile, writeFile } from "node:fs/promises";
import { register } from "node:module";
import { format, resolveConfig } from "prettier";

const check = process.argv.includes("--check");
register("./theme-source-loader.mjs", import.meta.url);
const { resolveBuiltInAppTheme, resolveBuiltInReaderTheme } =
  await import("../src/themes/resolveTheme.ts");
const { appThemeResolvedTokenRegistry, readerThemeResolvedTokenRegistry } =
  await import("../src/themes/themeTokenRegistry.ts");
const block = (selector, base) => {
  const theme = resolveBuiltInAppTheme(base);
  return `${selector} {\n  color-scheme: ${base};\n${Object.entries(appThemeResolvedTokenRegistry)
    .map(([key, { cssVariable }]) => `  ${cssVariable}: ${theme.tokens[key]};`)
    .join("\n")}\n}\n`;
};
const banner = "/* Generated by scripts/generate-built-in-palettes.mjs; do not edit. */\n";
const readerCss =
  banner +
  ["dark", "light", "sepia"]
    .map((base) => {
      const theme = resolveBuiltInReaderTheme(base);
      const selector =
        base === "dark" ? ".reader-page" : `.reader-page[data-reader-theme="${base}"]`;
      return `${selector} {\n${Object.entries(readerThemeResolvedTokenRegistry)
        .map(([key, { cssVariable }]) => `  ${cssVariable}: ${theme.tokens[key]};`)
        .join("\n")}\n}\n`;
    })
    .join("\n");
const css =
  banner +
  block(":root", "dark") +
  block('html[data-app-theme="light"]', "light") +
  `@media (prefers-color-scheme: light) {\n${block('html[data-app-theme="system"]', "light")}\n}\n`;
const startupPath = new URL("../public/appearance-startup.css", import.meta.url);
let startup = await readFile(startupPath, "utf8");
startup = startup.replace(/^\/\* Generated[^\n]*\n/, "");
const dark = resolveBuiltInAppTheme("dark").tokens;
for (const token of ["surface-main", "text"]) {
  if (!new RegExp(`var\\(--${token}, #[0-9a-f]+\\)`).test(startup)) {
    throw new Error(`Missing startup fallback for ${token}.`);
  }
}
startup = startup
  .replace(/var\(--surface-main, #[0-9a-f]+\)/, `var(--surface-main, ${dark.main})`)
  .replace(/var\(--text, #[0-9a-f]+\)/, `var(--text, ${dark.text})`);
for (const [relative, source] of [
  ["src/styles/built-in-palettes.css", css],
  ["src/styles/built-in-reader-palettes.css", readerCss],
  ["public/appearance-startup.css", banner + startup],
]) {
  const target = new URL(`../${relative}`, import.meta.url);
  const output = await format(source, { ...(await resolveConfig(target)), parser: "css" });
  if (check) {
    if ((await readFile(target, "utf8")) !== output)
      throw new Error(`Stale ${relative}; run pnpm run themes:generate.`);
  } else await writeFile(target, output);
}
console.log(
  check ? "Built-in palette outputs are current." : "Generated built-in palette outputs.",
);
